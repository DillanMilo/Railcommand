/* eslint-disable @typescript-eslint/no-require-imports */
const {chromium}=require('playwright');
const fs=require('node:fs');const assert=require('node:assert/strict');const path=require('node:path');
const base=process.env.RAILCOMMAND_E2E_BASE_URL || 'http://localhost:3017';
if (!['localhost','127.0.0.1','[::1]'].includes(new URL(base).hostname)) throw new Error('Use a local synthetic demo server for this acceptance script.');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.RAILCOMMAND_BROWSER_EXECUTABLE ? { executablePath: process.env.RAILCOMMAND_BROWSER_EXECUTABLE } : {})});
 const context=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true,extraHTTPHeaders:{"x-vercel-ip-country":"US"}});
 const fixture=fs.readFileSync(path.resolve(__dirname,'../public/IMG_0936.jpg'));
 const errors=[];
 await context.route('**/*',async route=>{const u=new URL(route.request().url());if(u.origin===new URL(base).origin)return route.continue();if(route.request().resourceType()==='image'||/\.(jpg|jpeg|png)/i.test(u.pathname))return route.fulfill({contentType:'image/jpeg',body:fixture});return route.abort();});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.goto(`${base}/login`);
  const demo=page.waitForResponse(r=>r.url().includes('/api/demo/local-session')&&r.request().method()==='POST');
  await page.getByRole('button',{name:/Explore Demo Project|Try demo project/i}).click();
  const demoResult=await demo; assert.equal(demoResult.status(),200, JSON.stringify({body:await demoResult.text(),origin:demoResult.request().headers().origin,url:demoResult.url()}));
  await page.waitForURL('**/dashboard');
  await page.goto(`${base}/projects/proj-001/daily-logs/new`);
  await page.getByRole('heading',{name:'New Daily Log',exact:true}).waitFor();
  await page.getByRole('button',{name:'Dismiss Supabase connection alert'}).click({timeout:2000}).catch(()=>{});
  await page.locator('input[type=date]').fill('2026-10-28');
  await page.getByPlaceholder(/Road Builders had a concrete crew/).fill('Synthetic photo library seed');
  await page.locator('input[type=file]').last().setInputFiles({name:'image.jpeg',mimeType:'image/jpeg',buffer:fixture});
  await page.getByLabel('Optional caption for photo 1').waitFor();
  await page.getByRole('button',{name:'Submit Log',exact:true}).click();
  await page.waitForURL('**/projects/proj-001/daily-logs');
  await page.getByRole('button',{name:'Dismiss Supabase connection alert'}).click({timeout:2000}).catch(()=>{});
  await page.getByRole('link',{name:'New Log',exact:true}).click();
  await page.locator('input[type=date]').fill('2026-10-29');
  await page.getByPlaceholder(/Road Builders had a concrete crew/).fill('Synthetic Caleb DFR caption acceptance');
  const library=page.locator('[data-slot=card]').filter({hasText:'Use photos already in RailCommand'});
  const add=library.getByRole('button',{name:/Add .*selected photo/});
  const grid=library.locator('div[class*="max-h"]');
  assert.ok((await add.boundingBox()).y<(await grid.boundingBox()).y,'Add control must precede the photo grid');
  await grid.getByRole('button').first().click();
  await add.click();
  await page.getByLabel('Optional caption for photo 1').fill('South entrance paving');
  await page.locator('input[type=file]').last().setInputFiles({name:'image.jpeg',mimeType:'image/jpeg',buffer:fixture});
  await page.getByLabel('Optional caption for photo 2').waitFor();
  const width=await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));assert.ok(width.scroll<=width.client+1);
  await library.scrollIntoViewIfNeeded();
  await page.screenshot({path:'/tmp/railcommand-caleb-picker-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Submit Log',exact:true}).click();
  await page.waitForURL('**/projects/proj-001/daily-logs');
  await page.getByRole('button',{name:'List',exact:true}).click();
  await page.getByRole('link').filter({hasText:'Synthetic Caleb DFR caption acceptance'}).first().click();
  await page.getByText('South entrance paving',{exact:true}).waitFor();
  await page.locator('img[alt="10/29/2026"]').waitFor();
  assert.equal(await page.locator('img[alt="image.jpeg"]').count(),0);
  await page.getByText('South entrance paving',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'/tmp/railcommand-caleb-dfr-mobile.png',fullPage:true});
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export PDF',exact:true}).click();
  await (await download).saveAs('/tmp/railcommand-caleb-dfr.pdf');
  await page.setViewportSize({width:1440,height:1050});
  await page.screenshot({path:'/tmp/railcommand-caleb-dfr-desktop.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({status:'passed',viewport:width,pdf:'/tmp/railcommand-caleb-dfr.pdf',checks:['add button above grid','library photo and imported photo','custom caption saved','blank caption defaults to report date','mobile and desktop DFR','PDF download','no page errors']}));
 }catch(e){await page.screenshot({path:'/tmp/railcommand-caleb-browser-failure.png',fullPage:true});throw e;}finally{await browser.close();}
})().catch(e=>{console.error(e.message);process.exit(1)});
